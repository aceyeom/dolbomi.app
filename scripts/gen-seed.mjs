// Writes supabase/seed.sql from src/data/works.js, the one place the index
// is edited. The seed is an upsert, so it can be run on a database that
// already has the rows: it brings them to what the file says and leaves any
// row the file does not name alone.
//
//   npm run gen:seed
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { works } from '../src/data/works.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)

const rows = works
  .map((w, i) => `  (${[q(w.slug), (i + 1) * 10, q(w.title), q(w.kind), q(w.year), q(w.note), q(w.href), q(w.plate)].join(', ')})`)
  .join(',\n')

const sql = `-- GENERATED by scripts/gen-seed.mjs from src/data/works.js. Do not edit by hand:
-- change that file and run \`npm run gen:seed\`.
--
-- The index of the room. Safe to run again.

insert into public.works (slug, position, title, kind, year, note, href, plate)
values
${rows}
on conflict (slug) do update set
  position = excluded.position,
  title = excluded.title,
  kind = excluded.kind,
  year = excluded.year,
  note = excluded.note,
  href = excluded.href,
  plate = excluded.plate,
  updated_at = now();
`
await writeFile(path.join(root, 'supabase/seed.sql'), sql)
console.log(`supabase/seed.sql: ${works.length} works`)
